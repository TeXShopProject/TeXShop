#!/usr/bin/env python3
"""Check/generate the typed dependency table from the reviewed contract.

The contract is authored from the requirement ledger, never reverse engineered
from controls under test. --ledger verifies the 13-column audit projection.
"""
from pathlib import Path
import argparse, json, re

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--write-source', action='store_true')
parser.add_argument('--ledger', type=Path)
args = parser.parse_args()
contract = json.loads((root/'Tests/Fixtures/SettingsDependencies.json').read_text())
rules = contract['rules']
lines = ['// Generated by Tests/check-settings-dependencies.py from the reviewed contract.']
outlets = set()
for rule in rules:
    assert len(rule['enabled_values']) == 1
    assert re.fullmatch(r'[A-Za-z][A-Za-z0-9]*', rule['key_symbol'])
    for outlet in rule['outlets']:
        assert outlet not in outlets and re.fullmatch(r'[A-Za-z][A-Za-z0-9]*', outlet)
        outlets.add(outlet)
        lines.append('        {TSSettingsCategory%s, %s, %d, _%s, %s},' % (
            rule['category'].capitalize(), rule['key_symbol'], int(rule['enabled_values'][0]),
            outlet, 'YES' if rule['whole_row'] else 'NO'))
text = '\n'.join(lines)+'\n'
target = root/'Sources/TSSettingsDependencies.inc'
if args.write_source:
    target.write_text(text)
assert target.read_text() == text, 'Dependency source differs from the reviewed contract'
if args.ledger:
    ledger = json.loads(args.ledger.read_text())
    projected = {json.dumps(rule,sort_keys=True) for control in ledger['controls']
                 for rule in control['dependencies'] if 'key_symbol' in rule}
    assert projected == {json.dumps(rule,sort_keys=True) for rule in rules}
assert len(outlets) == 16
print('PASS: 14 dependency conditions, 16 typed endpoints and reviewed projection')
