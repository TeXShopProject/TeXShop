#!/usr/bin/env python3
"""Build bundled English release documents with pdfLaTeX.

Requires TeX Live (including tgpagella and pdfpages). Run after updating the
release Markdown and About This Release.tex. An alternate notes directory lets
documentation be prepared without merging an unfinished website branch.
Supported Markdown: paragraphs, level 1/2 headings, flat dash lists, bold,
inline code, bare HTTP(S) URLs, and the release-status draft comment.
Other Markdown constructs are rejected instead of silently printed literally.
"""
import argparse
import re
import shutil
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def escaped(text):
    replacements = {'\\': r'\textbackslash{}', '{': r'\{', '}': r'\}',
                    '&': r'\&', '%': r'\%', '$': r'\$', '#': r'\#',
                    '_': r'\_', '~': r'\textasciitilde{}', '^': r'\textasciicircum{}',
                    '→': r'\(\rightarrow\)', '＋': '+', '〜': r'\textasciitilde{}',
                    '＼': r'\textbackslash{}'}
    return ''.join(replacements.get(c, c) for c in text)


def inline(text):
    tokens = re.split(r'(\*\*[^*]+\*\*|`[^`]+`|https?://\S+)', text)
    result = []
    for token in tokens:
        if re.fullmatch(r'\*\*[^*]+\*\*', token):
            result.append(r'\textbf{' + inline(token[2:-2]) + '}')
        elif re.fullmatch(r'`[^`]+`', token):
            result.append(r'\texttt{' + escaped(token[1:-1]) + '}')
        elif token.startswith(('https://', 'http://')):
            # Sentence punctuation and an enclosing parenthesis are not URL bytes.
            url = token
            while url:
                if url[-1] in '.,;:!?':
                    url = url[:-1]
                elif url[-1] in ')]' and url.count(url[-1]) > url.count({')': '(', ']': '['}[url[-1]]):
                    url = url[:-1]
                else:
                    break
            if any(c in url for c in '\\{}'):
                raise ValueError(f'Unsupported URL characters: {url!r}')
            result.append(r'\url{' + url + '}' + escaped(token[len(url):]))
        else:
            if re.search(r'[*`\[\]<>]|~~|(?<!\w)_(?=\S)|(?<=\S)_(?!\w)|\\[\W]', token):
                raise ValueError(f'Unsupported inline Markdown: {token!r}')
            result.append(escaped(token))
    return ''.join(result)


def markdown(text):
    output, listing = [], False
    for number, line in enumerate(text.splitlines(), 1):
        if line == '<!-- release-status: draft -->':
            output.append(r'\noindent\textit{Release preparation; not yet published.}\par')
            continue
        if (line[:1].isspace() or re.match(r'#{3,}|>|`{3,}|~{3,}|[+*] |\d+[.)] |[-*_]{3,}\s*$', line)
                or '|' in line or line.endswith('  ')):
            raise ValueError(f'Unsupported block Markdown on line {number}: {line!r}')
        if listing and not line.startswith('- '):
            output.append(r'\end{itemize}')
            listing = False
        if line.startswith('# '):
            output.append(r'\section{' + inline(line[2:]) + '}')
        elif line.startswith('## '):
            output.append(r'\subsection{' + inline(line[3:]) + '}')
        elif line.startswith('- '):
            if not listing:
                output.append(r'\begin{itemize}')
                listing = True
            output.append(r'\item ' + inline(line[2:]))
        elif line:
            output.append(inline(line) + '\n')
        else:
            output.append('')
    if listing:
        output.append(r'\end{itemize}')
    return '\n'.join(output)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--notes-dir', type=Path, default=ROOT / 'Documentation/Releases')
    parser.add_argument('--versions', nargs='+', default=['5.60', '5.59'])
    parser.add_argument('--latex', default='pdflatex')
    args = parser.parse_args()
    texts = []
    for version in args.versions:
        text = (args.notes_dir / f'{version}.md').read_text(encoding='utf-8')
        if not text.splitlines() or text.splitlines()[0] != f'# TeXShop {version}':
            raise ValueError(f'Wrong release heading: {version}')
        texts.append(markdown(text))
    source = r'''% Generated by Scripts/build-release-documents.py from release Markdown.
\documentclass[11pt,letterpaper]{article}
\usepackage[margin=1in]{geometry}
\usepackage[T1]{fontenc}
\usepackage{tgpagella}
\pdfinterwordspaceon
\usepackage{enumitem}
\setlist[itemize]{leftmargin=*,itemsep=.1em}
\usepackage{pdfpages}
\usepackage[colorlinks=true,urlcolor=blue,linkcolor=blue]{hyperref}
\hypersetup{pdftitle={TeXShop Changes},pdfauthor={TeXShop contributors}}
\setcounter{secnumdepth}{0}
\setlength{\parindent}{0pt}
\setlength{\parskip}{.3em}
\setlength{\emergencystretch}{2em}
\begin{document}
''' + '\n\\clearpage\n'.join(texts) + r'''
\clearpage
\pdfbookmark[0]{TeXShop 5.57 and earlier}{historical-changes}
\includepdf[pages=-]{Changes-5.57.pdf}
\end{document}
'''
    changes_dir = ROOT / 'ChangesDocument'
    changes_source = changes_dir / 'Changes.tex'
    changes_source.write_text(source, encoding='utf-8')
    about_source = ROOT / 'First Steps Source/About-This-Release/About This Release.tex'
    # Build away from the source tree so logs and auxiliary files stay untracked.
    with tempfile.TemporaryDirectory(prefix='texshop-release-docs-') as temp:
        output = Path(temp)
        built = []
        for tex in [changes_source, about_source]:
            for _ in range(2):
                subprocess.run([args.latex, '-interaction=nonstopmode', '-halt-on-error',
                                '-no-shell-escape', f'-output-directory={output}', tex.name],
                               cwd=tex.parent, check=True, stdout=subprocess.DEVNULL)
            log = (output / tex.with_suffix('.log').name).read_text(encoding='utf-8', errors='replace')
            if 'Missing character:' in log or 'Overfull \\hbox' in log or 'Overfull \\vbox' in log:
                warnings = '\n'.join(line for line in log.splitlines() if 'Missing character:' in line or 'Overfull ' in line)
                raise RuntimeError(f'Inspect layout warnings for {tex.name}:\n{warnings}')
            pdf = output / tex.with_suffix('.pdf').name
            built.append((tex, pdf))
        for tex, pdf in built:
            for destination in [tex.with_suffix('.pdf'),
                                ROOT / 'Resources/Interfaces/Base.lproj' / pdf.name,
                                ROOT / 'Resources/Interfaces/en.lproj' / pdf.name]:
                shutil.copy2(pdf, destination)
            print(f'Built and synchronized {pdf.name}')


if __name__ == '__main__':
    main()
